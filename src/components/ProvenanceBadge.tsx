import type { Provenance } from "@/lib/types";

type BadgeKind = "live" | "captured" | "fixture";

const styles: Record<BadgeKind, string> = {
  live: "bg-emerald-600 text-white",
  captured: "bg-amber-500 text-slate-950",
  fixture: "bg-slate-500 text-white",
};

const labels: Record<BadgeKind, string> = {
  live: "LIVE",
  captured: "CAPTURED",
  fixture: "DEMO FIXTURE",
};

export function Badge({ kind, detail }: { kind: BadgeKind; detail?: string }) {
  return (
    <span className="inline-flex flex-wrap items-center gap-2 text-xs">
      <span className={`rounded px-2 py-0.5 font-bold tracking-wider ${styles[kind]}`}>{labels[kind]}</span>
      {detail && <span className="text-slate-600 dark:text-slate-400">{detail}</span>}
    </span>
  );
}

export function formatTimestamp(iso?: string) {
  if (!iso) return "time unknown";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" });
}

export function ProvenanceBadge({ provenance }: { provenance: Provenance }) {
  switch (provenance.mode) {
    case "live":
      return <Badge kind="live" detail={`Flashpoint synthetic panel · n=${provenance.n}`} />;
    case "captured":
      return (
        <Badge
          kind="captured"
          detail={`Flashpoint synthetic run · ${formatTimestamp(provenance.capturedAt)} · n=${provenance.n}`}
        />
      );
    case "fixture":
      return <Badge kind="fixture" detail="No research was run" />;
  }
}

/** Shown whenever the respondents are synthetic personas. */
export function SyntheticNotice() {
  return (
    <div className="rounded-xl border border-amber-300 bg-amber-50 p-3 text-sm text-amber-900 dark:border-amber-800 dark:bg-amber-950/40 dark:text-amber-200">
      <strong>AI personas, not real people.</strong> These respondents are synthetic personas generated by
      Flashpoint. Treat the results as directional, not as evidence about real customers.
    </div>
  );
}
