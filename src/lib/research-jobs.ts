// Owner: P1. Live Flashpoint research runs as background jobs (server-only, in memory).
// One run: build the plan's survey -> run a synthetic panel through it -> ask Flashpoint to
// analyze the responses -> structure that analysis into findings with Claude.
// The browser polls /api/research/status; a run takes several minutes.
import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { ResearchPlan, ResearchProgress, ResearchResult } from "./types";
import { callTool, findId, findKey, FlashpointError, replyText } from "./flashpoint";
import { structureFindings } from "./claude";

const PANEL_POLL_MS = 30_000;
const PANEL_MAX_WAIT_MS = 40 * 60_000;
const MAX_PANEL = 30;

export const SYNTHETIC_CAVEAT =
  "Respondents are AI personas generated by Flashpoint's synthetic panel, not real people. Treat these results as directional.";

/** What a run has finished so far, so a retry after a late failure doesn't redo Flashpoint work. */
type Done = { surveyId?: string; conversationId?: string; panelId?: string; panelDone?: boolean; analysis?: string };
type Job = { id: string; key: string; result: ResearchResult; done: Done };

// Raw Flashpoint output of every live run, kept locally (git-ignored) as an audit trail.
const RUNS_DIR = path.join(process.cwd(), ".flashpoint", "runs");
async function saveRun(job: Job, plan: ResearchPlan) {
  try {
    await mkdir(RUNS_DIR, { recursive: true });
    await writeFile(path.join(RUNS_DIR, `${job.id}.json`), JSON.stringify({ plan, ...job.done, result: job.result }, null, 2));
  } catch (err) {
    console.error("could not save run", err);
  }
}

// Kept on globalThis so jobs survive dev-server hot reloads.
const g = globalThis as unknown as { __blindspotJobs?: Map<string, Job> };
const jobs = (g.__blindspotJobs ??= new Map());

const planKey = (plan: ResearchPlan) => JSON.stringify(plan.questions);

// Jobs started before `done` existed (kept across hot reloads) only have provenance; there a
// panelId was set only once the panel run had completed.
function doneSoFar(job: Job): Done {
  if (job.done) return job.done;
  const { surveyId, panelId } = job.result.provenance;
  return { ...(surveyId && { surveyId }), ...(panelId && { panelId, panelDone: true }) };
}

export function getJob(id: string) {
  return jobs.get(id)?.result;
}

/** Starts a live run for this plan, or returns the run already in progress for the same questions. */
export function startResearchJob(plan: ResearchPlan, token: string): ResearchResult {
  const key = planKey(plan);
  let resume: Done = {};
  for (const job of jobs.values()) {
    if (job.key !== key) continue;
    if (job.result.status !== "failed") return job.result;
    // Pick up where a failed run for the same questions stopped.
    const prior = doneSoFar(job);
    if (Object.keys(prior).length > Object.keys(resume).length) resume = prior;
  }
  const id = randomUUID();
  const startedAt = new Date().toISOString();
  const job: Job = {
    id,
    key,
    done: { ...resume },
    result: {
      status: "running",
      jobId: id,
      provenance: { mode: "live", source: "flashpoint_synthetic", platform: "flashpoint", n: 0 },
      findings: [],
      caveats: [SYNTHETIC_CAVEAT],
      progress: { stage: "building_survey", message: "Building the survey in Flashpoint", startedAt },
    },
  };
  jobs.set(id, job);
  runJob(job, plan, token).catch((err) => {
    const message =
      err instanceof FlashpointError || err instanceof Error ? err.message : "Live research failed";
    console.error(`research job ${id} failed: ${message}`);
    job.result = {
      ...job.result,
      status: "failed",
      progress: { ...job.result.progress!, stage: "failed", message },
    };
    void saveRun(job, plan);
  });
  return job.result;
}

function setProgress(job: Job, p: Partial<ResearchProgress>) {
  job.result = { ...job.result, progress: { ...job.result.progress!, fraction: undefined, ...p } };
}

function surveyBrief(plan: ResearchPlan) {
  const qs = plan.questions
    .map((q) => {
      const opts = q.options?.length ? "\n" + q.options.map((o) => `   - ${o}`).join("\n") : "";
      return `${q.id} (${q.type}): ${q.text}${opts}`;
    })
    .join("\n");
  return `Build a new survey that a synthetic panel will take.
Use EXACTLY these questions, in this order, with this wording and these answer options. Do not add, remove, reword or reorder anything, and do not add screener or demographic questions. For "scale" questions use the listed options as the scale points; "open_text" is a short open-ended answer.

Objective: ${plan.objective}
Target respondents: ${plan.targetSegment}

Questions:
${qs}

When it is built, publish it so a synthetic panel can take it. Do not recruit paid respondents and do not take any action that costs money. Reply with the survey_id.`;
}

const ANALYSIS_BRIEF = `Analyze the completed synthetic-panel responses to this survey. State the number of completed responses. For every question give the exact number of respondents who chose each answer option (per scale point for scale questions, per option for multi-select). For open-ended questions give the main themes with counts and up to 3 verbatim answers. Use only the response data; do not estimate or extrapolate. Do not export files and do not take any paid action.`;

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function runJob(job: Job, plan: ResearchPlan, token: string) {
  const done = job.done;
  // 1. Survey
  if (!done.surveyId) {
    const built = await callTool(token, "tool_survey", { brief: surveyBrief(plan) });
    done.surveyId = findId(built, "survey_id");
    done.conversationId = findId(built, "conversation_id");
    if (!done.surveyId) {
      throw new FlashpointError(
        `Flashpoint didn't return a survey id. Its reply: ${replyText(built).slice(0, 300)}`,
      );
    }
  }
  const surveyId = done.surveyId;
  job.result = { ...job.result, provenance: { ...job.result.provenance, surveyId } };
  if (!done.panelDone) await runPanel(job, plan, token, surveyId);
  const panelId = done.panelId;
  job.result = { ...job.result, provenance: { ...job.result.provenance, panelId } };

  // 3. Flashpoint's analysis of the responses
  if (!done.analysis) {
    setProgress(job, { stage: "analyzing", message: "Flashpoint is analyzing the responses" });
    const analysis = await callTool(token, "tool_survey", {
      brief: ANALYSIS_BRIEF,
      survey_id: surveyId,
      ...(done.conversationId && { conversation_id: done.conversationId }),
    });
    done.analysis = replyText(analysis);
    void saveRun(job, plan);
  }

  // 4. Structure into findings (Claude may only use numbers from the analysis)
  setProgress(job, { stage: "structuring", message: "Turning the analysis into findings" });
  const structured = await structureFindings(plan, done.analysis);

  job.result = {
    status: "completed",
    jobId: job.id,
    provenance: {
      mode: "live",
      source: "flashpoint_synthetic",
      platform: "flashpoint",
      surveyId,
      panelId,
      capturedAt: new Date().toISOString(),
      n: structured.n,
    },
    findings: structured.findings,
    caveats: [SYNTHETIC_CAVEAT, ...structured.caveats],
    progress: { ...job.result.progress!, stage: "done", message: "Done", fraction: undefined },
  };
  void saveRun(job, plan);
}

// 2. Synthetic panel: create personas, run them through the survey, poll until done.
async function runPanel(job: Job, plan: ResearchPlan, token: string, surveyId: string) {
  const done = job.done;
  const n = Math.max(5, Math.min(plan.sampleSize || MAX_PANEL, MAX_PANEL));
  setProgress(job, { stage: "running_panel", message: `Creating ${n} AI personas and running them through the survey` });
  const started = await callTool(token, "panel", {
    action: "create_and_run",
    name: `BlindSpot: ${plan.objective.slice(0, 60)}`,
    num_respondents: n,
    research_objective: `${plan.objective} Respondents: ${plan.targetSegment}`,
    survey_id: surveyId,
  });
  const panelJobId = findId(started, "job_id");
  if (!panelJobId) {
    throw new FlashpointError(`Flashpoint didn't start the panel run. Its reply: ${replyText(started).slice(0, 300)}`);
  }

  const deadline = Date.now() + PANEL_MAX_WAIT_MS;
  let panelId = findId(started, "panel_id");
  for (;;) {
    await sleep(PANEL_POLL_MS);
    const st = await callTool(token, "panel", { action: "status", job_id: panelJobId });
    panelId ??= findId(st, "panel_id");
    const status = String(findKey(st, "status") ?? "");
    const stage = findKey(st, "stage");
    const fraction = Number(findKey(st, "progress"));
    const message = findKey(st, "message");
    if (status === "completed") break;
    if (status === "failed" || status === "interrupted") {
      throw new FlashpointError(`Flashpoint panel run ${status}: ${String(findKey(st, "error") ?? message ?? "")}`.trim());
    }
    if (Date.now() > deadline) throw new FlashpointError("Flashpoint panel run took longer than 40 minutes; stopped waiting.");
    setProgress(job, {
      stage: "running_panel",
      message: `Panel running${stage ? ` (${String(stage)})` : ""}${typeof message === "string" && message ? `: ${message}` : ""}`,
      fraction: Number.isFinite(fraction) ? fraction : undefined,
    });
  }
  done.panelId = panelId;
  done.panelDone = true;
}
